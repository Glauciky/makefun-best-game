// Seeded random numbers (mulberry32). Gameplay uses the unseeded stream; the
// screenshot scenes seed it so a shot renders the same way every time.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function makeRng(seed) {
  const next = mulberry32(seed);
  return {
    next,
    range(min, max) { return min + next() * (max - min); },
    int(min, max) { return Math.floor(min + next() * (max - min + 1)); },
    pick(list) { return list[Math.floor(next() * list.length)]; },
    angle() { return next() * Math.PI * 2; },
  };
}

// The live game's stream: seeded once from the clock at load.
export const rng = makeRng((Date.now() ^ 0x9e3779b9) >>> 0);
